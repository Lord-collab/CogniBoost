              "Циркуль","Ежевика","Лабиринт","Фотограф","Зонтик"},
    };

    private static IReadOnlyList<TestQuestion> BuildMemoryQuestions()
    {
        var rng = new Random();
        var set = WordSets[rng.Next(WordSets.Length)];
        var questions = new List<TestQuestion>();

        // Показываем слова (специальный вопрос с флагом "запоминай")
        questions.Add(new TestQuestion(
            $"Запомни слова:\n\n{string.Join("  ·  ", set)}\n\nНажми «Далее» когда будешь готов",
            new[] { "Далее" }, 0));

        // 8 вопросов на распознавание
        for (var i = 0; i < 8; i++)
        {
            var correct = set[rng.Next(set.Length)];
            var wrong = new List<string>();
            var fillers = new[] {"Октябрь","Флейта","Стрела","Планета","Верблюд",
                                 "Горизонт","Лестница","Магнит","Жираф","Пепел"};
            while (wrong.Count < 3)
            {
                var w = fillers[rng.Next(fillers.Length)];
                if (!wrong.Contains(w) && !set.Contains(w)) wrong.Add(w);
            }
            var opts = new[] { correct, wrong[0], wrong[1], wrong[2] }.OrderBy(_ => rng.Next()).ToArray();
            questions.Add(new TestQuestion("Это слово было в списке?", opts,
                Array.IndexOf(opts, correct)));
        }

        return questions;
    }

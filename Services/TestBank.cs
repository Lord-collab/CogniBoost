    public static int CalculateIq(int correct, int total)
    {
        if (total <= 0) return 100;
        var ratio = correct / (double)total;
        double iq = ratio <= 0.6
            ? 70 + ratio / 0.6 * 30
            : 100 + (ratio - 0.6) / 0.4 * 45;
        return (int)Math.Round(iq);
    }

    public static string IqBand(int iq) => iq switch
    {
        >= 130 => "Очень высокий",
        >= 120 => "Высокий",
        >= 110 => "Выше среднего",
        >= 90  => "Средний",
        >= 80  => "Ниже среднего",
        _      => "Низкий"
    };


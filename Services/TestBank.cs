    // ─── Тест памяти (запомни слова) ─────────────────────────────────
    private static readonly string[][] WordSets =
    {
        new[]{"Яблоко","Ракета","Фонтан","Библиотека","Медведь",
              "Молния","Скрипка","Компас","Лопата","Радуга"},
